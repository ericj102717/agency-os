SCHEMA_SQL = """
CREATE TABLE IF NOT EXISTS action_center_actions (
    id TEXT PRIMARY KEY,
    business_id TEXT NOT NULL DEFAULT 'default',
    source TEXT NOT NULL DEFAULT 'manual',
    source_id TEXT,
    recommendation_id TEXT,
    title TEXT NOT NULL,
    description TEXT,
    priority TEXT NOT NULL DEFAULT 'medium',
    status TEXT NOT NULL DEFAULT 'new',
    action_type TEXT,
    entity_type TEXT,
    entity_id TEXT,
    entity_name TEXT,
    due_at TEXT,
    snoozed_until TEXT,
    completed_at TEXT,
    dismissed_at TEXT,
    notes TEXT,
    outcome TEXT,
    metadata_json TEXT,
    created_at TEXT NOT NULL DEFAULT (datetime('now')),
    updated_at TEXT NOT NULL DEFAULT (datetime('now'))
);

CREATE TABLE IF NOT EXISTS action_center_events (
    id TEXT PRIMARY KEY,
    action_id TEXT NOT NULL,
    event_type TEXT NOT NULL,
    from_status TEXT,
    to_status TEXT,
    note TEXT,
    outcome TEXT,
    metadata_json TEXT,
    created_at TEXT NOT NULL DEFAULT (datetime('now'))
);

CREATE INDEX IF NOT EXISTS idx_aca_business_id ON action_center_actions(business_id);
CREATE INDEX IF NOT EXISTS idx_aca_status ON action_center_actions(status);
CREATE INDEX IF NOT EXISTS idx_aca_priority ON action_center_actions(priority);
CREATE INDEX IF NOT EXISTS idx_aca_source_id ON action_center_actions(source_id);
CREATE INDEX IF NOT EXISTS idx_ace_action_id ON action_center_events(action_id);
"""

VALID_STATUSES = {"new", "approved", "in_progress", "waiting", "snoozed", "done", "dismissed"}
VALID_PRIORITIES = {"high", "medium", "low"}
ACTIVE_STATUSES = {"new", "approved", "in_progress", "waiting"}
CLOSED_STATUSES = {"snoozed", "done", "dismissed"}

def init_db():
    """Initialize the actions schema."""
    conn = get_conn()
    conn.executescript(SCHEMA_SQL)
    conn.commit()
    return_conn(conn)

