def _row_to_dict(row) -> Dict[str, Any]:
    """Convert a DB row to a dict."""
    if row is None:
        return None
    if isinstance(row, dict):
        d = dict(row)
    elif hasattr(row, "keys"):
        d = {k: row[k] for k in row.keys()}
    else:
        d = dict(row)
    # Parse metadata_json
    if d.get("metadata_json"):
        try:
            d["metadata"] = json.loads(d["metadata_json"])
        except (json.JSONDecodeError, TypeError):
            d["metadata"] = {}
    else:
        d["metadata"] = {}
    d.pop("metadata_json", None)
    return d

def get_actions(
    business_id: str = "default",
    status: Optional[str] = None,
    priority: Optional[str] = None,
    source: Optional[str] = None,
    include_closed: bool = False,
    limit: int = 100,
) -> Tuple[List[Dict], Dict[str, int]]:
    """Get actions with optional filters. Returns (actions, counts)."""
    conn = get_conn()
    
    where_clauses = ["business_id = ?"]
    params = [business_id]
    
    if status and status != "all":
        where_clauses.append("status = ?")
        params.append(status)
    elif not include_closed:
        # Exclude closed statuses unless explicitly included
        placeholders = ",".join(["?" for _ in ACTIVE_STATUSES])
        where_clauses.append(f"status IN ({placeholders})")
        params.extend(list(ACTIVE_STATUSES))
    
    if priority:
        where_clauses.append("priority = ?")
        params.append(priority)
    
    if source:
        where_clauses.append("source = ?")
        params.append(source)
    
    where_sql = " AND ".join(where_clauses)
    params.append(limit)
    
    rows = conn.execute(
        f"SELECT * FROM action_center_actions WHERE {where_sql} ORDER BY \
        CASE priority WHEN 'high' THEN 0 WHEN 'medium' THEN 1 WHEN 'low' THEN 2 ELSE 3 END, \
        created_at ASC LIMIT ?",
        params
    ).fetchall()
    
    actions = [_row_to_dict(r) for r in rows]
    
    # Get counts by status
    count_rows = conn.execute(
        "SELECT status, COUNT(*) as cnt FROM action_center_actions WHERE business_id = ? GROUP BY status",
        [business_id]
    ).fetchall()
    
    counts = {s: 0 for s in VALID_STATUSES}
    for cr in count_rows:
        s = cr["status"] if hasattr(cr, "__getitem__") else cr[0]
        c = cr["cnt"] if hasattr(cr, "__getitem__") else cr[1]
        counts[s] = c
    
    return_conn(conn)
    return actions, counts

def get_action(action_id: str) -> Optional[Dict]:
    """Get a single action by ID."""
    conn = get_conn()
    row = conn.execute("SELECT * FROM action_center_actions WHERE id = ?", [action_id]).fetchone()
    return_conn(conn)
    return _row_to_dict(row)

def get_action_events(action_id: str) -> List[Dict]:
    """Get all events for an action."""
    conn = get_conn()
    rows = conn.execute(
        "SELECT * FROM action_center_events WHERE action_id = ? ORDER BY created_at ASC",
        [action_id]
    ).fetchall()
    return_conn(conn)
    return [_row_to_dict(r) for r in rows]

def create_action(
    business_id: str = "default",
    source: str = "manual",
    source_id: Optional[str] = None,
    recommendation_id: Optional[str] = None,
    title: str = "",
    description: Optional[str] = None,
    priority: str = "medium",
    action_type: Optional[str] = None,
    entity_type: Optional[str] = None,
    entity_id: Optional[str] = None,
    entity_name: Optional[str] = None,
    due_at: Optional[str] = None,
    notes: Optional[str] = None,
    metadata: Optional[Dict] = None,
) -> Dict:
    """Create a new action."""
    action_id = str(uuid.uuid4())
    now = datetime.utcnow().isoformat()
    meta_json = json.dumps(metadata) if metadata else None
    
    conn = get_conn()
    conn.execute(
        """INSERT INTO action_center_actions (
            id, business_id, source, source_id, recommendation_id,
            title, description, priority, status,
            action_type, entity_type, entity_id, entity_name,
            due_at, notes, metadata_json, created_at, updated_at
        ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, 'new', ?, ?, ?, ?, ?, ?, ?, ?, ?)""",
        [action_id, business_id, source, source_id, recommendation_id,
         title, description, priority,
         action_type, entity_type, entity_id, entity_name,
         due_at, notes, meta_json, now, now]
    )
    
    # Create initial event
    event_id = str(uuid.uuid4())
    conn.execute(
        """INSERT INTO action_center_events (id, action_id, event_type, to_status, created_at)
        VALUES (?, ?, 'created', 'new', ?)""",
        [event_id, action_id, now]
    )
    
    conn.commit()
    return_conn(conn)
    return get_action(action_id)

def update_action(action_id: str, updates: Dict[str, Any]) -> Optional[Dict]:
    """Partially update an action. Returns updated action or None if not found."""
    existing = get_action(action_id)
    if not existing:
        return None
    
    allowed_fields = {
        "title", "description", "priority", "status",
        "action_type", "entity_type", "entity_id", "entity_name",
        "due_at", "snoozed_until", "completed_at", "dismissed_at",
        "notes", "outcome"
    }
    
    set_clauses = []
    params = []
    old_status = existing.get("status", "new")
    new_status = old_status
    
    for key, value in updates.items():
        if key not in allowed_fields:
            continue
        if key == "status":
            if value not in VALID_STATUSES:
                raise ValueError(f"Invalid status: {value}. Must be one of {VALID_STATUSES}")
            new_status = value
            # Set timestamp fields based on status
            now = datetime.utcnow().isoformat()
            if value == "done" and not updates.get("completed_at"):
                set_clauses.append("completed_at = ?")
                params.append(now)
            elif value == "dismissed" and not updates.get("dismissed_at"):
                set_clauses.append("dismissed_at = ?")
                params.append(now)
        set_clauses.append(f"{key} = ?")
        params.append(value)
    
    if not set_clauses:
        return existing
    
    now = datetime.utcnow().isoformat()
    set_clauses.append("updated_at = ?")
    params.append(now)
    params.append(action_id)
    
    conn = get_conn()
    conn.execute(
        f"UPDATE action_center_actions SET {', '.join(set_clauses)} WHERE id = ?",
        params
    )
    
    # Create status change event if status changed
    if new_status != old_status:
        event_id = str(uuid.uuid4())
        conn.execute(
            """INSERT INTO action_center_events (id, action_id, event_type, from_status, to_status, note, created_at)
            VALUES (?, ?, 'status_changed', ?, ?, ?, ?)""",
            [event_id, action_id, old_status, new_status,
             updates.get("notes", "") if updates.get("notes") else None, now]
        )
    
    conn.commit()
    return_conn(conn)
    return get_action(action_id)

def add_event(
    action_id: str,
    event_type: str,
    note: Optional[str] = None,
    outcome: Optional[str] = None,
    metadata: Optional[Dict] = None,
) -> Dict:
    """Add an event to an action's history."""
    event_id = str(uuid.uuid4())
    now = datetime.utcnow().isoformat()
    meta_json = json.dumps(metadata) if metadata else None
    
    conn = get_conn()
    conn.execute(
        """INSERT INTO action_center_events (id, action_id, event_type, note, outcome, metadata_json, created_at)
        VALUES (?, ?, ?, ?, ?, ?, ?)""",
        [event_id, action_id, event_type, note, outcome, meta_json, now]
    )
    conn.commit()
    return_conn(conn)
    return {
        "id": event_id,
        "action_id": action_id,
        "event_type": event_type,
        "note": note,
        "outcome": outcome,
        "metadata": metadata or {},
        "created_at": now,
    }

