def seed_demo_actions(business_id: str = "roofing"):
    """Seed demo actions if none exist yet. Idempotent — won't overwrite existing."""
    conn = get_conn()
    
    # Check if any demo actions already exist
    existing = conn.execute(
        "SELECT COUNT(*) as cnt FROM action_center_actions WHERE business_id = ? AND source = 'demo'",
        [business_id]
    ).fetchone()
    count = existing["cnt"] if existing else 0
    
    if count > 0:
        return_conn(conn)
        return {"seeded": 0, "existing": count, "message": "Demo actions already exist"}
    
    now = datetime.utcnow().isoformat()
    seeded = 0
    
    for action in DEMO_ACTIONS:
        action_id = str(uuid.uuid4())
        source_id = action["source_id"]
        
        # Check if this specific source_id already exists (idempotent)
        existing_row = conn.execute(
            "SELECT id FROM action_center_actions WHERE business_id = ? AND source_id = ?",
            [business_id, source_id]
        ).fetchone()
        
        if existing_row:
            continue
        
        conn.execute(
            """INSERT INTO action_center_actions (
                id, business_id, source, source_id,
                title, description, priority, status,
                action_type, entity_type, entity_id, entity_name,
                created_at, updated_at
            ) VALUES (?, ?, 'demo', ?, ?, ?, ?, 'new', ?, ?, ?, ?, ?, ?)""",
            [action_id, business_id, source_id,
             action["title"], action["description"], action["priority"],
             action.get("action_type"), action.get("entity_type"),
             action.get("entity_id"), action.get("entity_name"),
             now, now]
        )
        
        # Create initial event
        event_id = str(uuid.uuid4())
        conn.execute(
            """INSERT INTO action_center_events (id, action_id, event_type, to_status, created_at)
            VALUES (?, ?, 'created', 'new', ?)""",
            [event_id, action_id, now]
        )
        seeded += 1
    
    conn.commit()
    return_conn(conn)
    return {"seeded": seeded, "existing": 0, "message": f"Seeded {seeded} demo actions"}

def has_actions(business_id: str = "default") -> bool:
    """Check if any actions exist for a business."""
    conn = get_conn()
    row = conn.execute(
        "SELECT COUNT(*) as cnt FROM action_center_actions WHERE business_id = ?",
        [business_id]
    ).fetchone()
    count = row["cnt"] if row else 0
    return_conn(conn)
    return count > 0
