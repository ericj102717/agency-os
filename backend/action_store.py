#!/usr/bin/env python3
"""
Action Store
============
Persistent storage for the Action Execution Center.
Manages actions (tasks generated by recommendations) and action_events (audit trail).

Tables:
  - actions: trackable tasks with 7-state pipeline
  - action_events: execution ledger of all status changes and notes

Status flow: new → approved → in_progress → waiting → done
             (snoozed and dismissed are side states)
"""

import json
import uuid
import os
from datetime import datetime
from typing import Any, Dict, List, Optional, Tuple

# Use db.py abstraction (Postgres when DATABASE_URL is set, SQLite fallback)
try:
    import db as _db
    DB_TYPE = _db.DB_TYPE
except ImportError:
    _db = None
    DB_TYPE = "sqlite"

import sqlite3 as _sqlite3

DB_PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)), "data.db")

# Connection helpers (reuse data_store pattern)
_conn = None

def get_conn():
    if _db and _db.DB_TYPE == "postgres":
        return _db.get_conn()
    global _conn
    if _conn is None:
        _conn = _sqlite3.connect(DB_PATH, check_same_thread=False)
        _conn.row_factory = _sqlite3.Row
        _conn.execute("PRAGMA journal_mode=WAL")
    return _conn

def return_conn(conn):
    if _db and _db.DB_TYPE == "postgres":
        _db.return_conn(conn)
        return
    pass  # SQLite uses shared connection

